"""Generate docs/RULES.md from each check's RULES catalog (so the docs cannot drift from the code).

Usage: python -m benchmarks.gen_rules [--out docs/RULES.md]
"""
from __future__ import annotations

import argparse
import importlib
from pathlib import Path

PACKAGES = ("checksnap.checks.dataset", "checksnap.checks.optimization")


def render() -> str:
    lines = ["# Rules", "", "Generated by `python -m benchmarks.gen_rules`. Do not edit by hand.", ""]
    for pkg in PACKAGES:
        try:
            rules = importlib.import_module(pkg).RULES
        except Exception as exc:  # noqa: BLE001  a missing check must not break doc generation
            lines += [f"## {pkg.rsplit('.', 1)[1]}", "", f"_Not available: {type(exc).__name__}: {exc}_", ""]
            continue
        lines += [f"## {pkg.rsplit('.', 1)[1]}", "", "| Rule | Severity | Snap | Title |", "|---|---|---|---|"]
        for r in sorted(rules.values(), key=lambda r: r.id):
            lines.append(f"| `{r.id}` | {getattr(r.severity, 'name', r.severity)} | {'yes' if r.needs_snap else 'no'} | {r.title} |")
        lines.append("")
        for r in sorted(rules.values(), key=lambda r: r.id):
            lines += [f"### {r.id}: {r.title}", "", r.explanation, "", f"**Fix:** {r.fix_hint}", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(Path(__file__).resolve().parents[1] / "docs" / "RULES.md"))
    args = ap.parse_args(argv)
    Path(args.out).write_text(render(), encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
